//! Real-time engine diagnostic metrics and frame budget tracking.

use std::time::Duration;

/// Diagnostic telemetry and performance metrics collected across frame execution.
#[derive(Debug, Clone, Default)]
pub struct DiagnosticMetrics {
    /// Rolling frames per second (FPS).
    pub fps: f32,
    /// Last frame delta time in milliseconds.
    pub frame_time_ms: f32,
    /// Count of fixed simulation ticks executed in the most recent frame.
    pub fixed_updates_this_frame: u32,
    /// Total fixed ticks executed since engine startup.
    pub total_fixed_ticks: u64,
    /// Total frames rendered since engine startup.
    pub total_frames: u64,
    /// Number of draw calls issued this frame.
    pub draw_calls: u32,
    /// Number of active dynamic lights assigned to froxels.
    pub froxel_light_count: u32,
    /// Number of 2D quads generated by UI this frame.
    pub ui_quad_count: u32,
    /// Fractional remainder for transform interpolation between fixed frames in `[0.0, 1.0)`.
    pub alpha: f32,
    /// Scratch arena allocated bytes in the most recent frame.
    pub allocated_scratch_bytes: usize,
}

impl DiagnosticMetrics {
    /// Returns `true` if the frame execution time exceeded the allotted budget.
    #[must_use]
    pub fn is_budget_exceeded(&self, budget_ms: f32) -> bool {
        self.frame_time_ms > budget_ms
    }

    /// Records a completed frame with elapsed duration.
    pub fn record_frame(&mut self, elapsed: Duration) {
        let ms = elapsed.as_secs_f32() * 1000.0;
        self.frame_time_ms = ms;
        if elapsed.as_secs_f32() > 0.0 {
            let instant_fps = 1.0 / elapsed.as_secs_f32();
            // Smooth rolling average FPS (alpha = 0.1)
            if self.fps == 0.0 {
                self.fps = instant_fps;
            } else {
                self.fps = self.fps * 0.9 + instant_fps * 0.1;
            }
        }
        self.total_frames += 1;
    }
}
