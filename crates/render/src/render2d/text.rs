//! Embedded 8x8 bitmap font and GPU glyph atlas for 2D text rendering.
//!
//! Provides [`BitmapFont2d`], which packs the 95 printable ASCII characters (`0x20..=0x7E`)
//! into a `128x64` RGBA8 texture (`16` columns by `8` rows of `8x8` cells) with white ink
//! (`[255, 255, 255, 255]`) on a transparent background (`[0, 0, 0, 0]`).

use crate::render2d::atlas::{Rect2d, TextureAtlas2d};
use korppi_math::{Vec2, Vec4};
use korppi_rhi::{
    GraphicsDevice, RhiError, SampleCount, TextureDescriptor, TextureDimension, TextureFormat,
    TextureHandle, TextureUsage,
};

/// Width of one glyph cell in texels.
pub const GLYPH_WIDTH: u32 = 8;
/// Height of one glyph cell in texels.
pub const GLYPH_HEIGHT: u32 = 8;
/// Number of glyph columns in the default font atlas.
const ATLAS_COLS: u32 = 16;
/// Number of glyph rows in the default font atlas.
const ATLAS_ROWS: u32 = 8;
/// Total width of the default font atlas texture in texels.
pub const FONT_ATLAS_WIDTH: u32 = ATLAS_COLS * GLYPH_WIDTH;
/// Total height of the default font atlas texture in texels.
pub const FONT_ATLAS_HEIGHT: u32 = ATLAS_ROWS * GLYPH_HEIGHT;

const FIRST_ASCII: u8 = 0x20;
const LAST_ASCII: u8 = 0x7E;
const GLYPH_COUNT: usize = (LAST_ASCII - FIRST_ASCII + 1) as usize;

/// 8x8 bitmap font backed by a GPU texture and [`TextureAtlas2d`].
#[derive(Debug)]
pub struct BitmapFont2d {
    texture: TextureHandle,
    atlas: TextureAtlas2d,
    glyph_width: f32,
    glyph_height: f32,
}

impl BitmapFont2d {
    /// Uploads the embedded 8x8 printable-ASCII bitmap font to `device`.
    pub fn create_default(device: &dyn GraphicsDevice) -> Result<Self, RhiError> {
        let mut pixels = vec![0u8; (FONT_ATLAS_WIDTH * FONT_ATLAS_HEIGHT * 4) as usize];
        let mut atlas = TextureAtlas2d::new(FONT_ATLAS_WIDTH, FONT_ATLAS_HEIGHT);

        for (idx, glyph) in ASCII_8X8_GLYPHS.iter().enumerate() {
            let col = (idx as u32) % ATLAS_COLS;
            let row = (idx as u32) / ATLAS_COLS;
            let cell_x = col * GLYPH_WIDTH;
            let cell_y = row * GLYPH_HEIGHT;

            for (gy, &bits) in glyph.iter().enumerate() {
                for gx in 0..GLYPH_WIDTH {
                    let bit_set = ((bits >> (7 - gx)) & 1) != 0;
                    if bit_set {
                        let px = cell_x + gx;
                        let py = cell_y + gy as u32;
                        let offset = ((py * FONT_ATLAS_WIDTH + px) * 4) as usize;
                        pixels[offset..offset + 4].copy_from_slice(&[255, 255, 255, 255]);
                    }
                }
            }

            let ch = (FIRST_ASCII + idx as u8) as char;
            let mut name_buf = [0u8; 4];
            let name = ch.encode_utf8(&mut name_buf);
            atlas.add_region(
                name,
                Rect2d {
                    x: cell_x as f32,
                    y: cell_y as f32,
                    width: GLYPH_WIDTH as f32,
                    height: GLYPH_HEIGHT as f32,
                },
            );
        }

        let texture = device.create_texture(
            &TextureDescriptor {
                width: FONT_ATLAS_WIDTH,
                height: FONT_ATLAS_HEIGHT,
                depth: 1,
                array_layers: 1,
                mip_levels: 1,
                sample_count: SampleCount::Count1,
                format: TextureFormat::Rgba8Unorm,
                usage: TextureUsage::SAMPLED,
                dimension: TextureDimension::D2,
                label: Some("bitmap_font_2d_atlas"),
            },
            Some(&pixels),
        )?;

        Ok(Self {
            texture,
            atlas,
            glyph_width: GLYPH_WIDTH as f32,
            glyph_height: GLYPH_HEIGHT as f32,
        })
    }

    /// Returns the GPU texture handle of the glyph atlas.
    #[inline]
    pub fn texture(&self) -> TextureHandle {
        self.texture
    }

    /// Returns the underlying [`TextureAtlas2d`] describing each glyph cell.
    #[inline]
    pub fn atlas(&self) -> &TextureAtlas2d {
        &self.atlas
    }

    /// Returns the normalized `[u_min, v_min, u_max, v_max]` UV rectangle for `ch`.
    ///
    /// Non-printable or non-ASCII characters fall back to `'?'`.
    #[inline]
    pub fn glyph_uv(&self, ch: char) -> Option<Vec4> {
        let code = if (FIRST_ASCII as char..=LAST_ASCII as char).contains(&ch) {
            ch as u8
        } else {
            b'?'
        };
        let region_id = (code - FIRST_ASCII) as usize;
        self.atlas.get_uv(region_id)
    }

    /// Returns the canvas dimensions of a single character cell at `scale`.
    #[inline]
    pub fn glyph_size(&self, scale: f32) -> Vec2 {
        Vec2::new(self.glyph_width * scale, self.glyph_height * scale)
    }

    /// Measures the bounding box size in canvas units of `text` rendered at `scale`.
    pub fn measure_text(&self, text: &str, scale: f32) -> Vec2 {
        if text.is_empty() {
            return Vec2::ZERO;
        }
        let cell = self.glyph_size(scale);
        let mut max_cols = 0usize;
        let mut cur_cols = 0usize;
        let mut lines = 1usize;
        for ch in text.chars() {
            if ch == '\n' {
                max_cols = max_cols.max(cur_cols);
                cur_cols = 0;
                lines += 1;
            } else {
                cur_cols += 1;
            }
        }
        max_cols = max_cols.max(cur_cols);
        Vec2::new(max_cols as f32 * cell.x, lines as f32 * cell.y)
    }

    /// Destroys the GPU glyph atlas texture.
    pub fn destroy(self, device: &dyn GraphicsDevice) -> Result<(), RhiError> {
        device.destroy_texture(self.texture)
    }
}

